#!/usr/bin/env python3
"""Generate DDA / trig tables for Wolf64 (The Keep style, 40 columns)."""

from __future__ import annotations

import math
from pathlib import Path

OUT = Path(__file__).resolve().parents[1] / "src" / "tables.asm"
COLS = 40
# SquareDoom / Keep-adapted half-FOV in 256ths of a circle (≈42° half → ~84° full)
HALF_FOV_256 = 30


def main() -> None:
    # Column angles: same formula as Squaredoom/tools/gentables.js
    ang_b = []
    for col in range(COLS):
        t = (col + 0.5) / COLS - 0.5
        a = int(round(t * 2 * HALF_FOV_256)) & 255
        ang_b.append(a)

    # Fish-eye: 255·cos(signed angtab) — Keep correction for 40 cols
    fish = []
    for a in ang_b:
        signed = a if a < 128 else a - 256
        rad = signed * 2 * math.pi / 256
        fish.append(max(1, min(255, int(round(255 * math.cos(rad))))))

    # fixsec[0..64] = 256 / cos(i * 90/64 degrees) in 8.8 — The Keep table
    fixsecl = [
        0x00, 0x00, 0x00, 0x01, 0x01, 0x02, 0x03, 0x04, 0x05, 0x06, 0x08, 0x0A, 0x0C, 0x0E, 0x10, 0x12,
        0x15, 0x18, 0x1B, 0x1F, 0x22, 0x26, 0x2A, 0x2F, 0x34, 0x39, 0x3F, 0x45, 0x4B, 0x52, 0x5A, 0x61,
        0x6A, 0x73, 0x7D, 0x88, 0x94, 0xA0, 0xAE, 0xBD, 0xCD, 0xDF, 0xF2, 0x07, 0x1F, 0x39, 0x57, 0x78,
        0x9D, 0xC7, 0xF8, 0x30, 0x72, 0xC0, 0x1E, 0x90, 0x20, 0xD9, 0xD1, 0x2B, 0x34, 0x98, 0x61, 0xBF,
        0x00,
    ]
    fixsech = [
        0x01, 0x01, 0x01, 0x01, 0x01, 0x01, 0x01, 0x01, 0x01, 0x01, 0x01, 0x01, 0x01, 0x01, 0x01, 0x01,
        0x01, 0x01, 0x01, 0x01, 0x01, 0x01, 0x01, 0x01, 0x01, 0x01, 0x01, 0x01, 0x01, 0x01, 0x01, 0x01,
        0x01, 0x01, 0x01, 0x01, 0x01, 0x01, 0x01, 0x01, 0x01, 0x01, 0x01, 0x02, 0x02, 0x02, 0x02, 0x02,
        0x02, 0x02, 0x02, 0x03, 0x03, 0x03, 0x04, 0x04, 0x05, 0x05, 0x06, 0x08, 0x0A, 0x0D, 0x14, 0x28,
        0x40,
    ]
    fixcos = [
        0xFF, 0xFF, 0xFF, 0xFE, 0xFE, 0xFD, 0xFC, 0xFB, 0xFA, 0xF9, 0xF7, 0xF6, 0xF4, 0xF2, 0xF0, 0xEE,
        0xEC, 0xE9, 0xE7, 0xE4, 0xE1, 0xDE, 0xDB, 0xD7, 0xD4, 0xD0, 0xCD, 0xC9, 0xC5, 0xC1, 0xBD, 0xB9,
        0xB4, 0xB0, 0xAB, 0xA7, 0xA2, 0x9D, 0x98, 0x93, 0x8E, 0x88, 0x83, 0x7E, 0x78, 0x73, 0x6D, 0x67,
        0x62, 0x5C, 0x56, 0x50, 0x4A, 0x44, 0x3E, 0x38, 0x32, 0x2C, 0x25, 0x1F, 0x19, 0x13, 0x0D, 0x06,
        0x00,
    ]

    # sintab: 256 entries, amp 64 (SquareDoom / movement)
    sintab = [int(round(math.sin(i * 2 * math.pi / 256) * 64)) & 255 for i in range(256 + 64)]

    # Half-height 1..12 from wallz high byte (≈ tiles).
    # 16/z → at spawn (~3 tiles) half_h≈5 with visible sky/floor.
    heightab = []
    for wz in range(256):
        if wz == 0:
            h = 12
        else:
            h = min(12, max(1, 16 // wz))
        heightab.append(h)

    # Column bases into transposed FB at $E000 (24 bytes/col for char rows 1..24)
    VIEW_ROWS = 24
    colbaselo = [(c * VIEW_ROWS) & 255 for c in range(COLS)]
    colbasehi = [0xE0 + ((c * VIEW_ROWS) >> 8) for c in range(COLS)]

    def bchunk(name: str, data: list[int], w: int = 16) -> str:
        lines = [f"{name}"]
        for i in range(0, len(data), w):
            chunk = data[i : i + w]
            lines.append("\t!byte " + ",".join(f"${b:02x}" for b in chunk))
        return "\n".join(lines) + "\n"

    parts = [
        "; Auto-generated by tools/gentables.py — do not edit\n",
        bchunk("angtab", ang_b),
        bchunk("fishtab", fish),
        bchunk("fixsecl", fixsecl),
        bchunk("fixsech", fixsech),
        bchunk("fixcos", fixcos),
        bchunk("heightab", heightab, 16),
        bchunk("colbaselo", colbaselo),
        bchunk("colbasehi", colbasehi),
        bchunk("sintab", sintab),
        "costab = sintab + 64\n",
    ]
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("".join(parts), encoding="utf-8")
    print(f"Wrote {OUT}")


if __name__ == "__main__":
    main()
